# 문제 2. 4개 매장 × 3개월 매출 [[100, 120, 90], [80, 95, 110], [150, 140, 160], [60, 70, 65]]에서 매장별 총매출과 월별 평균을 구하세요.

import numpy as np  # 넘파이 (관례적으로 np 라는 별명)
sales = np.array([[100, 120, 90], [80, 95, 110], [150, 140, 160], [60, 70, 65]])
print("매장별 총매출:", sales.sum(axis=1))
print("월별 평균:", sales.mean(axis=0))
