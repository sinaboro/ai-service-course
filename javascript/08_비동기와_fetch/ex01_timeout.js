// ex01_timeout.js : 코드는 위에서 아래로 실행되지만, "기다리는 일" 은 뒤로 미뤄져요

console.log("1. 주문 받기");

// setTimeout(함수, 밀리초): 정해진 시간이 지난 뒤에 함수를 불러요 (1000 = 1초)
setTimeout(() => {
  console.log("3. 1초 뒤: 커피 완성!");
}, 1000);

// 기다리는 동안 멈추지 않고 다음 줄로 바로 가요
console.log("2. 다음 손님 주문 받기");

// 이렇게 "기다리는 일을 맡겨 두고 다른 일을 먼저 하는 것" 이 비동기예요
