# 인덱싱과 슬라이싱
s = "PYTHON"
#    012345   (앞에서부터 번호)
#   -654321   (뒤에서부터 번호)

print(s[0])      # 첫 글자
print(s[3])
print(s[-1])     # 마지막 글자
print(s[0:2])    # 0번부터 2번 "앞"까지
print(s[2:])     # 2번부터 끝까지
print(s[:3])     # 처음부터 3번 앞까지
print(s[::2])    # 2칸씩 건너뛰며
print(s[::-1])   # 거꾸로

jumin = "990315-1234567"
