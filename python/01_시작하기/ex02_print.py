# print() 의 여러 가지 사용법
print("사과", "바나나", "포도")          # 쉼표로 여러 값 → 사이에 공백 하나
print("사과", "바나나", "포도", sep="/")  # sep: 값 사이에 넣을 글자
print("줄을 바꾸지 않고", end=" ")        # end: 출력 끝에 붙일 글자 (기본은 줄바꿈)
print("이어서 출력")
print(10 + 20)                           # 계산 결과도 출력
print("10 + 20")                         # 따옴표 안은 그냥 글자
print("=" * 20)                          # 글자 반복
